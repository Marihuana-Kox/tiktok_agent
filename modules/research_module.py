from openai import OpenAI
import config

client = OpenAI(api_key=config.OPENAI_API_KEY)

def gather_facts(topic: str, user_intro: str = "") -> dict:
    """Собирает факты и информацию по теме"""
    
    prompt = f"""
    Ты — исследователь для TikTok-канала о загадках истории.
    Твоя задача: собрать МАКСИМУМ конкретных фактов по теме.
    
    Тема: {topic}
    {f"Вступление автора: {user_intro}" if user_intro else ""}
    
    СОБЕРИ ИНФОРМАЦИЮ ПО БЛОКАМ:
    
    1. ОСНОВНЫЕ ФАКТЫ:
       - Даты (минимум 3-5 конкретных дат)
       - Имена (кто участвовал, исследователи, правители)
       - Места (где находится, локации)
       - Размеры/веса/количества (конкретные цифры)
    
    2. ОФИЦИАЛЬНАЯ ВЕРСИЯ:
       - Что говорит наука/история
       - Когда и кем было открыто/построено
       - Принятая датировка
    
    3. ПАРАДОКСЫ И ПРОТИВОРЕЧИЯ:
       - Что не сходится в официальной версии
       - Технологические несоответствия
       - Логистические проблемы
       - Хронологические нестыковки
    
    4. АЛЬТЕРНАТИВНЫЕ ВЕРСИИ:
       - Какие есть теории
       - Кто их выдвигает
       - Аргументы за и против
    
    5. ИНТЕРЕСНЫЕ ДЕТАЛИ:
       - Малоизвестные факты
       - Современные исследования
       - Археологические находки
    
    ФОРМАТ ВЫВОДА:
    Пиши конкретно, без воды. Каждый факт — отдельная строка.
    Минимум 15-20 конкретных фактов всего.
    """
    
    response = client.chat.completions.create(
        model=config.TEXT_MODEL,
        messages=[{"role": "user", "content": prompt}],
        temperature=0.7,
        max_tokens=2000
    )
    
    return response.choices[0].message.content