from openai import OpenAI
import config

client = OpenAI(api_key=config.OPENAI_API_KEY)

def create_plan(topic: str, facts: str) -> dict:
    """Создаёт план статьи на основе собранных фактов"""
    
    prompt = f"""
    Ты — сценарист для TikTok. На основе собранных фактов создай план статьи.
    
    ТЕМА: {topic}
    
    СОБРАННЫЕ ФАКТЫ:
    {facts}
    
    ЗАДАЧА:
    Создай УНИКАЛЬНУЮ структуру статьи. НЕ используй шаблон!
    
    Проанализируй факты и определи:
    1. Какой факт самый шокирующий — это будет ХУК
    2. Какие парадоксы самые сильные — это ОСНОВА
    3. Какой вопрос самый провокационный — это ФИНАЛ
    
    СТРУКТУРА ПЛАНА:
    
    === НАЗВАНИЕ ===
    (предложи 3 варианта цепляющих названий)
    
    === ХУК (0-10 сек) ===
    - Какой факт использовать
    - Как сформулировать (пример)
    
    === ОСНОВНАЯ ЧАСТЬ (10-50 сек) ===
    Разбей на 2-4 логических блока:
    - Блок 1: [тема блока] — какие факты использовать
    - Блок 2: [тема блока] — какие факты использовать
    - и т.д.
    
    === ФИНАЛ (50-60 сек) ===
    - Какой вопрос задать зрителю
    - Как сформулировать призыв
    
    === КЛЮЧЕВЫЕ ФРАЗЫ ===
    (5-7 сильных фраз которые должны быть в тексте)
    
    === ХЭШТЕГИ ===
    (5 релевантных хэштегов)
    
    ВАЖНО: План должен быть уникальным для этой темы, не шаблонным!
    """
    
    response = client.chat.completions.create(
        model=config.TEXT_MODEL,
        messages=[{"role": "user", "content": prompt}],
        temperature=0.8,
        max_tokens=1500
    )
    
    return response.choices[0].message.content