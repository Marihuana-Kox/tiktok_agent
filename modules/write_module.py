from openai import OpenAI
import config
from modules.prompt_loader import load_prompt
from modules.author_loader import load_author_style, format_author_prompt

client = OpenAI(api_key=config.OPENAI_API_KEY)

# === ДЕФОЛТНЫЙ ПРОМПТ (если файл не выбран) ===
DEFAULT_PROMPT = """
Ты — ведущий альтернативного исторического расследования для TikTok.
Твой стиль: "монолог удивлённого интеллектуала" — уверенно, с фактами, без воды.

=== ЖЁСТКИЕ ПРАВИЛА ===

❌ ЗАПРЕЩЕНО:
- Фразы: "вызывает вопросы", "оставляет недоумение", "звучит сенсационно"
- Более 2 риторических вопросов подряд без факта между ними
- Шаблонные призывы: "подпишитесь", "не пропустите", "ставьте лайк"
- Общие утверждения без цифр: "огромный", "древний", "сложный"
- Слова: "некоторые исследователи", "учёные считают" (конкретизируй!)

✅ ОБЯЗАТЕЛЬНО:
- Минимум 3 КОНКРЕТНЫХ ФАКТОВ (даты, имена, числа, размеры, веса)
- Минимум 2 СРАВНЕНИЯ с современностью или другими эпохами
- Минимум 2 ПАРАДОКСА с цифрами ("X тонн, но без Y технологии")
- 1 СМЕЛОЕ ЗАЯВЛЕНИЕ на грани конспирологии в конце
- Авторский стиль из user_intro использовать в КАЖДОМ абзаце

=== СТРУКТУРА ===

ХУК (1 абзац):
- Шок-факт с цифрой в первом предложении
- Сразу парадокс ("но при этом...")
- Никаких "знали ли вы", "представьте себе"

ОСНОВА (2-3 абзаца):
- Каждый абзац = 1 факт + 1 сравнение + 1 вопрос
- Конкретные имена: не "исследователь", а "Ричард Хоу в 1997 году"
- Конкретные цифры: не "тяжёлые блоки", а "блоки по 200 тонн"

АЛЬТЕРНАТИВА (1 абзац):
- Смелая теория без "а что если"
- Утвердительно: "вероятно", "возможно", "есть свидетельства"
- Минимум 2 аргумента в поддержку

ФИНАЛ (1 абзац):
- Вопрос который провоцирует спор, не просто "что думаете"
- Без шаблонных призывов к подписке
- Оставь зрителя с мыслью которую нельзя игнорировать

=== ПРИМЕРЫ КОНКРЕТИКИ ===

❌ ПЛОХО: "Древние строители использовали сложные технологии"
✅ ХОРОШО: "В 2560 году до н.э. 20 000 рабочих укладывали 2.3 миллиона блоков за 20 лет"

❌ ПЛОХО: "Блоки были очень тяжёлые"
✅ ХОРОШО: "Гранитные балки по 80 тонн поднимали на высоту 40 метров без кранов"

❌ ПЛОХО: "Следы обработки вызывают вопросы"
✅ ХОРОШО: "Спилы глубиной 3мм с шагом 1мм — точность алмазного резака 20 века"

❌ ПЛОХО: "Древние строители использовали сложные технологии"
✅ ХОРОШО: "Вероятнее всего эти древние строители не строили пирамиды а нашли их и приспособили под свои нужды"

=== ПРОВЕРКА ПЕРЕД ВЫВОДОМ ===

Посчитай:
- [ ] Минимум 2 конкретных цифр в тексте?
- [ ] Минимум 2 имени/названия?
- [ ] Минимум 2 сравнения ("в то время как", "но при этом")?
- [ ] Нет шаблонных призывов в конце?
- [ ] Есть смелое заявление в последнем абзаце?

Если нет — ДОПИШИ перед выводом!
"""

def write_article(topic: str, facts: str, plan: str, topic_notes: str = "", prompt_style: str = None) -> str:
    """
    Пишет статью по плану со стилем автора.
    
    Args:
        topic: тема статьи
        facts: собранные факты
        plan: план статьи
        topic_notes: заметки по конкретной теме (опционально)
        prompt_style: имя файла промпта (опционально)
    """
    
    # === ЗАГРУЖАЕМ СТИЛЬ АВТОРА ===
    try:
        author_style = load_author_style()
        author_prompt = format_author_prompt(author_style)
    except Exception as e:
        print(f"⚠️ Не удалось загрузить стиль автора: {e}")
        author_prompt = "Пиши живо, с фактами, без воды."
   
    # === ЗАГРУЖАЕМ ПРОМПТ ===
    if prompt_style:
        try:
            system_prompt = load_prompt(prompt_style, random_select=False)
        except Exception as e:
            print(f"⚠️ Не удалось загрузить промпт: {e}")
            print("📄 Использую дефолтный промпт...")
            system_prompt = DEFAULT_PROMPT
    else:
        system_prompt = DEFAULT_PROMPT
    
    # === БЛОК ЗАМЕТОК ПО ТЕМЕ ===
    notes_block = ""
    if topic_notes:
        notes_block = f"""

=== ЗАМЕТКИ ПО ТЕМЕ ===
{topic_notes}
Учти эти детали в тексте.
"""
    
    # === ФОРМИРУЕМ ЗАПРОС ===
    prompt = f"""
{author_prompt}

{system_prompt}

=== ТЕМА СТАТЬИ ===
{topic}

=== СОБРАННЫЕ ФАКТЫ ===
{facts}

=== ПЛАН СТАТЬИ ===
{plan}{notes_block}

=== ЗАДАЧА ===
Напиши полноценную статью для TikTok следуя плану, стилю автора и промпту выше.

ТРЕБОВАНИЯ:
1. ФОРМАТ: Только абзацы, без списков и нумерации
2. ДЛИНА: 300-500 слов
3. СТРУКТУРА ВЫВОДА:
   === НАЗВАНИЕ ===
   === ОПИСАНИЕ ===
   === ТЕКСТ ДЛЯ ОЗВУЧКИ ===
   === ХЭШТЕГИ ===
"""
    
    response = client.chat.completions.create(
        model=config.TEXT_MODEL,
        messages=[{"role": "user", "content": prompt}],
        temperature=0.9,
        max_tokens=config.MAX_TOKENS
    )
    
    return response.choices[0].message.content